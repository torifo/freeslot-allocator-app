// Regenerates test/fixtures/qr_frames/*.json from the hub's own encoder, so the
// Dart codec in lib/services/sync/qr_chunk_codec.dart is always checked against
// the TypeScript one rather than against frames someone typed by hand.
//
//   node --experimental-strip-types tools/hub/scripts/gen-qr-fixtures.mjs
//
// Each fixture keeps its `value` and `chunkChars`; only `frames` (and the note)
// are rewritten. To add a fixture, drop a file with those two keys in place and
// run this again.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { encodeFrames } from '../src/qr-codec.ts';

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, '..', '..', '..', 'test', 'fixtures', 'qr_frames');
const NOTE =
  'Generated by tools/hub/scripts/gen-qr-fixtures.mjs from ' +
  'tools/hub/src/qr-codec.ts (Node zlib gzip level 9). Do not hand-edit.';

for (const name of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const path = join(dir, name);
  const fixture = JSON.parse(readFileSync(path, 'utf8'));
  const chunkChars = fixture.chunkChars;
  if (typeof chunkChars !== 'number') throw new Error(`${name}: missing chunkChars`);
  const frames = encodeFrames(fixture.value, { chunkChars });
  writeFileSync(path, `${JSON.stringify({ note: NOTE, chunkChars, value: fixture.value, frames }, null, 2)}\n`);
  console.log(`${name}: ${frames.length} frame(s)`);
}
